function createClubCrestSvgDataUrl(code: string, primaryColor: string, secondaryColor: string): string {
  const cleanCode = (code || 'FC').slice(0, 3).toUpperCase().replace(/[^A-Z0-9]/g, '') || 'FC';
  const p = /^#[0-9A-Fa-f]{3,8}$/.test(primaryColor) ? primaryColor : '#0891B2';
  const s = /^#[0-9A-Fa-f]{3,8}$/.test(secondaryColor) ? secondaryColor : '#0B1528';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${s}"/><stop offset="100%" stop-color="${p}"/></linearGradient></defs><path d="M60 8 L104 22 V62 C104 88 84 106 60 114 C36 106 16 88 16 62 V22 Z" fill="url(#g)" stroke="#FFFFFF" stroke-width="4"/><text x="60" y="68" text-anchor="middle" font-family="Arial,sans-serif" font-weight="700" font-size="24" fill="#FFFFFF">${cleanCode}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

