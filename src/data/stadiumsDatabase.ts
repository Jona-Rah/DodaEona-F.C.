// Builds the full list of stadiums mapped cleanly to clubs
export function buildAllClubStadiums(): StadiumRecord[] {
  const stadiums: StadiumRecord[] = [];

  for (let i = 0; i < FC27_COMPACT_TEAMS.length; i++) {
    const tuple = FC27_COMPACT_TEAMS[i];
    const [
      id,
      name,
      shortName,
      code,
      country,
      league,
      gender,
      primaryColor,
      secondaryColor,
      stadiumName,
    ] = tuple;

    const lowerStadium = (stadiumName || '').toLowerCase().trim();
    const lowerClub = (name || '').toLowerCase().trim();
    const overrideKey = CLUB_TO_VERIFIED_STADIUM_KEY[lowerClub];
    const verified =
      VERIFIED_STADIUMS_CATALOG[lowerStadium] ||
      (overrideKey ? VERIFIED_STADIUMS_CATALOG[overrideKey] : undefined);

    let lat = 0;
    let lng = 0;
    let city = '';
    let resolvedCountry = country;
    let capacity = gender === 'women' ? 15000 : 25000;
    let yearOpened: number | undefined;
    let surface = 'Natural Grass';
    let imageUrl = VERIFIED_STADIUM_PHOTOS[i % VERIFIED_STADIUM_PHOTOS.length];
    let description = `${name} competes in ${league} (${country}). Pin centers on the ${country} hub in ${REGIONAL_CITY_COORDINATES[country]?.city || country}; open Google Maps directions for specific ground routing.`;
    let isVerifiedStadium = false;

    if (verified) {
      lat = verified.lat;
      lng = verified.lng;
      city = verified.city;
      resolvedCountry = verified.country || country;
      capacity = verified.capacity;
      yearOpened = verified.yearOpened;
      if (verified.surface) surface = verified.surface;
      if (verified.imageUrl) imageUrl = verified.imageUrl;
      if (verified.description) description = verified.description;
      isVerifiedStadium = true;
    } else {
      const regional = REGIONAL_CITY_COORDINATES[country] || {
        city: country,
        lat: 48.856614,
        lng: 2.352222,
      };
      lat = regional.lat;
      lng = regional.lng;
      city = regional.city;
    }

    const countryCode = getCountryCode(resolvedCountry) || getCountryCode(country) || 'EU';
    const flagEmoji = getCountryFlag(resolvedCountry) || getCountryFlag(country);
    const fallbackCrestUrl = createClubCrestSvgDataUrl(code, primaryColor, secondaryColor);
    const clubCrestUrl = getRealClubLogo(name, shortName, code) || fallbackCrestUrl;

    const resolvedName = verified?.canonicalName || stadiumName;
    const queryStr = encodeURIComponent(
      isVerifiedStadium ? `${resolvedName}, ${city}, ${resolvedCountry}` : `${name}, ${resolvedCountry}`
    );
    const mapsSearchUrl = `https://www.google.com/maps/search/?api=1&query=${queryStr}`;
    const streetViewUrl = `https://www.google.com/maps/@?api=1&map_action=pano&viewpoint=${lat},${lng}`;

    stadiums.push({
      id: `stadium-${id}`,
      name: resolvedName,
      clubId: id,
      clubName: name,
      clubShortName: shortName,
      clubCode: code,
      clubCrestUrl,
      fallbackCrestUrl,
      primaryColor,
      secondaryColor,
      gender,
      city,
      country: resolvedCountry,
      countryCode,
      flagEmoji,
      league,
      capacity,
      yearOpened,
      surface,
      coordinates: { lat, lng },
      isVerifiedStadium,
      imageUrl,
      description,
      mapsSearchUrl,
      streetViewUrl,
    });
  }

  return stadiums;
}

// Singleton cache for instantaneous querying
let _cachedStadiums: StadiumRecord[] | null = null;

export function getAllStadiums(): StadiumRecord[] {
  if (!_cachedStadiums) {
    _cachedStadiums = buildAllClubStadiums();
  }
  return _cachedStadiums;
}

export function getStadiumByClubId(clubId: string): StadiumRecord | undefined {
  return getAllStadiums().find((s) => s.clubId === clubId);
}

const STADIUM_NON_ASCII_RE = /[^\u0000-\u007f]/;

function normalizeSearchText(input: string): string {
  if (!input) return '';
  if (!STADIUM_NON_ASCII_RE.test(input)) {
    return input.toLowerCase().trim();
  }
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ø/gi, 'o')
    .replace(/ł/gi, 'l')
    .replace(/ı/gi, 'i')
    .replace(/ß/gi, 'ss')
    .toLowerCase()
    .trim();
}

interface IndexedStadiumSearchRow {
  stadium: StadiumRecord;
  clubN: string;
  shortN: string;
  stadN: string;
  codeN: string;
  cityN: string;
  countryN: string;
  leagueN: string;
}

const stadiumSearchCache = new WeakMap<StadiumRecord[], IndexedStadiumSearchRow[]>();

function getIndexedStadiumRows(pool: StadiumRecord[]): IndexedStadiumSearchRow[] {
  const cached = stadiumSearchCache.get(pool);
  if (cached) return cached;

  const rows: IndexedStadiumSearchRow[] = new Array(pool.length);
  for (let i = 0; i < pool.length; i++) {
    const s = pool[i];
    rows[i] = {
      stadium: s,
      clubN: normalizeSearchText(s.clubName),
      shortN: normalizeSearchText(s.clubShortName),
      stadN: normalizeSearchText(s.name),
      codeN: normalizeSearchText(s.clubCode),
      cityN: normalizeSearchText(s.city),
      countryN: normalizeSearchText(s.country),
      leagueN: normalizeSearchText(s.league),
    };
  }
  stadiumSearchCache.set(pool, rows);
  return rows;
}

export function searchStadiums(query: string, stadiums?: StadiumRecord[]): StadiumRecord[] {
  const pool = stadiums || getAllStadiums();
  const q = normalizeSearchText(query);
  if (!q) return pool;

  const rows = getIndexedStadiumRows(pool);
  const qHasWomen = q.includes('women');
  const scored: Array<{ stadium: StadiumRecord; score: number }> = [];

  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    const s = r.stadium;

    let score = 0;
    if (r.clubN === q || r.shortN === q || r.stadN === q) score += 120;
    else if (r.codeN === q) score += 95;
    else if (r.clubN.startsWith(q) || r.shortN.startsWith(q) || r.stadN.startsWith(q)) score += 75;
    else if (r.clubN.includes(q) || r.shortN.includes(q) || r.stadN.includes(q)) score += 50;
    else if (r.cityN.startsWith(q)) score += 40;
    else if (r.cityN.includes(q) || r.countryN.includes(q) || r.leagueN.includes(q)) score += 20;

    if (score > 0) {
      if (s.isVerifiedStadium) score += 15;
      if (s.gender === 'men') score += 1;
      if (qHasWomen && s.gender === 'women') score += 25;
      scored.push({ stadium: s, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || b.stadium.capacity - a.stadium.capacity);
  return scored.map((item) => item.stadium);
}
